def data_files():
    for folder in DATA:
        for path in sorted((HERE / folder).rglob("*")):
            if path.is_file() and path.name != ".DS_Store":
                yield path.relative_to(HERE).as_posix(), path.read_bytes()


def build():
    out = [HEADER, "\n\nSOURCES = {\n"]
    for name in MODULES:
        source = (HERE / f"{name}.py").read_text(encoding="utf-8")
        literal = "r'''" + source + "'''"
        if ast.literal_eval(literal) != source:
            raise SystemExit(f"{name}.py can't be held in a r''' string")
        out.append(f'"{name}": {literal},\n')
    out.append("}\n\nFILES = {\n")
    for name, data in data_files():
        out.append(f'"{name}": "{base64.b64encode(zlib.compress(data, 9)).decode()}",\n')
    out.append('}\n\nif __name__ == "__main__":\n    sys.exit(run())\n')
    return "".join(out)


if __name__ == "__main__":
    OUT.write_text(build(), encoding="utf-8")
    OUT.chmod(0o755)
    print(f"{OUT}: {OUT.stat().st_size:,} bytes")
